export function buildSoulPolicyPrompt(surface: SoulPolicySurface): string {
  const agentSoul = readRootFile('prompts/agent-soul.md').trim()
  const surfaceLines = SURFACE_POLICIES[surface]
  const interactionLines = surface === 'yinyi' || surface === 'portrait' || surface === 'care' ? [] : INTERACTION_POLICY
  return `<soul_policy surface="${surface}">
<agent_soul>
${agentSoul || FALLBACK_AGENT_SOUL}
</agent_soul>

<core_contract>
${CORE_POLICY.map((line) => `- ${line}`).join('\n')}
</core_contract>

<surface_contract>
${[...interactionLines, ...surfaceLines].map((line) => `- ${line}`).join('\n')}
</surface_contract>
</soul_policy>`
}
